/// The canonical name behind an exact alias in `table`.
pub(super) fn lookup(table: &[(&str, &'static str)], alias: &str) -> Option<&'static str> {
    table
        .iter()
        .find_map(|&(candidate, canonical)| (candidate == alias).then_some(canonical))
}
