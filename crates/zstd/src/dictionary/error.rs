//! Original dictionary authoring refusals and their borrowed native fields.

use super::FastCoverTuned;
use crate::decoding::errors::HuffmanTableError;
use purrdf_hash::error::StructuredError;
use std::{fmt, vec::Vec};

/// The corpus that supplied the refused entropy statistics.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StatisticsSource {
    /// The supplied training sample.
    Sample,
    /// The raw dictionary content used as fallback statistics.
    RawContent,
}

/// A dictionary could not be trained, finalized or written.
///
/// Native causes and already constructed statistic buffers move into the error.
/// Neither construction nor inspection renders an I/O or entropy failure.
#[derive(Debug)]
#[non_exhaustive]
pub enum Error {
    /// Reading the original training source failed.
    SourceRead {
        /// Original I/O owner, including its caller-supplied payload.
        cause: std::io::Error,
        /// Bytes read into the sample before the refusal.
        bytes_read: usize,
    },
    /// Writing the constructed dictionary failed.
    OutputWrite {
        /// Original I/O owner, including its caller-supplied payload.
        cause: std::io::Error,
        /// Dictionary bytes supplied to `write_all`, not a partial-write count.
        output_bytes: usize,
    },
    /// The generated Huffman table was refused by the native decoder.
    GeneratedHuffman {
        /// Original entropy decoder refusal.
        cause: HuffmanTableError,
        /// Original statistics used by the encoder.
        statistics: Vec<u8>,
        /// Original generated bytes supplied to the decoder.
        encoded: Vec<u8>,
    },
    /// Neither supported weight representation can encode the rebalanced table.
    UnrepresentableHuffman {
        /// Bounded statistics extent before deterministic rebalancing.
        original_statistics_bytes: usize,
        /// Actual rebalanced statistics supplied to the table builder.
        statistics: Vec<u8>,
    },
    /// Raw dictionary content is empty.
    EmptyRawContent {
        /// Requested finalized dictionary size.
        dict_size: usize,
        /// Original supplied sample extent.
        sample_bytes: usize,
    },
    /// The requested dictionary identifier is zero.
    ZeroDictionaryId {
        /// Original refused identifier.
        dict_id: u32,
    },
    /// The actual entropy counts contain fewer than two observations.
    InsufficientSymbolStatistics {
        /// Corpus actually selected, including fallback selection.
        source: StatisticsSource,
        /// Original supplied sample extent.
        sample_bytes: usize,
        /// Original raw-content extent.
        raw_content_bytes: usize,
        /// Maximum symbol passed to the table builder.
        max_symbol: u8,
        /// Maximum table log passed to the table builder.
        max_log: u8,
        /// Original computed observation count.
        total: usize,
        /// Original ordered per-symbol counts.
        counts: Vec<usize>,
    },
    /// The requested size cannot hold the computed header and minimum content.
    DictionarySizeTooSmall {
        /// Original requested finalized size.
        dict_size: usize,
        /// Actual serialized header size, including offset history.
        header_len: usize,
        /// Original minimum content requirement.
        min_content_size: usize,
    },
    /// The training sample is empty.
    EmptyTrainingSample {
        /// Original requested dictionary size.
        dict_size: usize,
    },
    /// Training produced no dictionary for a nonzero requested size.
    TrainingSampleTooSmall {
        /// Original sample extent.
        sample_bytes: usize,
        /// Actual dictionary budget supplied to training.
        dict_size: usize,
        /// Actual training output extent.
        produced_bytes: usize,
        /// Actual selected, normalized training parameters and coverage score.
        tuned: FastCoverTuned,
    },
}

impl Error {
    fn native_cause(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::SourceRead { cause, .. } | Self::OutputWrite { cause, .. } => Some(cause),
            Self::GeneratedHuffman { cause, .. } => Some(cause),
            Self::UnrepresentableHuffman { .. }
            | Self::EmptyRawContent { .. }
            | Self::ZeroDictionaryId { .. }
            | Self::InsufficientSymbolStatistics { .. }
            | Self::DictionarySizeTooSmall { .. }
            | Self::EmptyTrainingSample { .. }
            | Self::TrainingSampleTooSmall { .. } => None,
        }
    }
}

purrdf_hash::error_sources!(Error, native native_cause);

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::SourceRead { cause, .. } | Self::OutputWrite { cause, .. } => {
                fmt::Display::fmt(cause, f)
            }
            Self::GeneratedHuffman { cause, .. } => {
                write!(f, "failed to decode generated huffman table: {cause}")
            }
            Self::UnrepresentableHuffman { .. } => {
                f.write_str("generated huffman table has no writable weight representation")
            }
            Self::EmptyRawContent { .. } => f.write_str("raw dictionary content must not be empty"),
            Self::ZeroDictionaryId { .. } => f.write_str("dictionary id must be non-zero"),
            Self::InsufficientSymbolStatistics { .. } => {
                f.write_str("insufficient symbol statistics for FSE table")
            }
            Self::DictionarySizeTooSmall { .. } => {
                f.write_str("dictionary size too small to fit header and offset history")
            }
            Self::EmptyTrainingSample { .. } => f.write_str("source stream is empty"),
            Self::TrainingSampleTooSmall { .. } => {
                f.write_str("training sample is too small for FastCOVER")
            }
        }
    }
}

impl StructuredError for FastCoverTuned {
    purrdf_hash::error_visit! {
        @record self { k, d, f, accel, score } => "zstd-fastcover-tuned" {
            "k" => ByteCount(self.k as u128), "d" => ByteCount(self.d as u128),
            "f" => Unsigned(u128::from(self.f)), "accel" => Unsigned(self.accel as u128),
            "score" => Unsigned(self.score as u128),
        }
    }
}

impl StructuredError for Error {
    purrdf_hash::error_visit! {
        SourceRead { cause, bytes_read } => "zstd-dictionary-source-read" {
            "cause" => Cause(cause), "bytes_read" => ByteCount(*bytes_read as u128),
        },
        OutputWrite { cause, output_bytes } => "zstd-dictionary-output-write" {
            "cause" => Cause(cause), "output_bytes" => ByteCount(*output_bytes as u128),
        },
        GeneratedHuffman { cause, statistics, encoded } => "zstd-dictionary-generated-huffman" {
            "cause" => Cause(cause), "statistics" => Bytes(statistics), "encoded" => Bytes(encoded),
        },
        UnrepresentableHuffman { original_statistics_bytes, statistics } => "zstd-dictionary-unrepresentable-huffman" {
            "original_statistics_bytes" => ByteCount(*original_statistics_bytes as u128),
            "statistics" => Bytes(statistics),
        },
        EmptyRawContent { dict_size, sample_bytes } => "zstd-dictionary-empty-raw-content" {
            "dict_size" => ByteCount(*dict_size as u128), "sample_bytes" => ByteCount(*sample_bytes as u128),
        },
        ZeroDictionaryId { dict_id } => "zstd-dictionary-zero-id" {
            "dict_id" => Unsigned(u128::from(*dict_id)),
        },
        InsufficientSymbolStatistics { source, sample_bytes, raw_content_bytes, max_symbol, max_log, total, counts } => "zstd-dictionary-insufficient-symbol-statistics" {
            "source" => Code(match source { StatisticsSource::Sample => "sample", StatisticsSource::RawContent => "raw-content" }),
            "sample_bytes" => ByteCount(*sample_bytes as u128), "raw_content_bytes" => ByteCount(*raw_content_bytes as u128),
            "max_symbol" => Unsigned(u128::from(*max_symbol)), "max_log" => Unsigned(u128::from(*max_log)),
            "total" => Unsigned(*total as u128),
            "counts" => List(counts.iter().map(|count| purrdf_hash::error::ErrorValue::Unsigned(*count as u128))),
        },
        DictionarySizeTooSmall { dict_size, header_len, min_content_size } => "zstd-dictionary-size-too-small" {
            "dict_size" => ByteCount(*dict_size as u128), "header_len" => ByteCount(*header_len as u128),
            "min_content_size" => ByteCount(*min_content_size as u128),
        },
        EmptyTrainingSample { dict_size } => "zstd-dictionary-empty-training-sample" {
            "dict_size" => ByteCount(*dict_size as u128),
        },
        TrainingSampleTooSmall { sample_bytes, dict_size, produced_bytes, tuned } => "zstd-dictionary-training-sample-too-small" {
            "sample_bytes" => ByteCount(*sample_bytes as u128), "dict_size" => ByteCount(*dict_size as u128),
            "produced_bytes" => ByteCount(*produced_bytes as u128), "tuned" => Record(tuned),
        },
    }
}
