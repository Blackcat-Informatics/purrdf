//! OPTIMISED: the same result as LITERAL with the shortcuts the text permits.
//!
//! * Partition as structure of arrays per side: element array, the inverse
//!   position and cell start of each vertex (global arrays: a vertex lives in
//!   exactly one partition at a time), and per cell start its live length and
//!   its extent. A colour is a cell start, an order-preserving renaming of the
//!   text's colour (8.2), so removed vertices leave dead slots instead of
//!   moving the cells after them.
//! * One undo trail per partition (splits and deletions) and one log of fixed
//!   nodes, in place of a copy per child.
//! * Lazy restriction: after a FIX the removed vertices are deleted from their
//!   cells, the one component whose search did not finish stays in place and
//!   only the other components are copied out.
//! * Incremental component discovery: interleaved searches from the lines of
//!   the fixed nodes, stopped when all but one have finished.
//! * Pruning in a branching call: orbits of the group generated by the
//!   automorphisms found (from children of equal certificate, in this call or a
//!   nested one), twins, the child's own entries, and the smallest entries of
//!   its nested calls.
//! * No recursion: calls, nests and branching calls are frames of one explicit
//!   stack.

