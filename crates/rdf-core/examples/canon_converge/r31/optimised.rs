/// A branching call (rule 3) in progress.
#[derive(Debug)]
struct Branch {
    pi: usize,
    p: u64,
    depth: u64,
    c: u32,
    target: Vec<u32>,
    next: usize,
    best: Option<(Vec<u32>, Chosen)>,
    cur_inv: Vec<u32>,
    tried: Vec<u32>,
    orbits: Uf,
    twins: Uf,
    marks: (usize, usize, usize),
}

#[derive(Debug)]
enum Frame {
    Call { pi: usize, p: u64, depth: u64 },
    Nest(Box<Nest>),
    Branch(Box<Branch>),
}

/// A node's lines as `(rank, nodes with the node itself replaced)`, sorted.
type TwinSignature = Vec<(u32, Vec<u32>)>;

/// One interleaved component search.
#[derive(Debug, Default)]
struct Search {
    queue: VecDeque<(u8, u32)>,
    members: [Vec<u32>; 2],
}

struct Engine<'a> {
    input: &'a Input,
    options: Options,
    stats: Stats,
    node_lines: Vec<Vec<u32>>,
    /// Per node, `(line, slot)` of each incidence; `slot` indexes `line_adj`.
    node_adj: Vec<Vec<(u32, u32)>>,
    line_off: Vec<u32>,
    line_adj: Vec<u32>,
    /// The current label of each incidence, encoded (see `encode`).
    line_lab: Vec<u128>,
    /// How often the node of each incidence occurs in its line.
    line_rep: Vec<u32>,
    /// Rank of `[masked text, count]` of each line (5.6).
    rank: Vec<u32>,
    free: Vec<bool>,
    pos: Vec<u64>,
    fixed_log: Vec<u32>,
    at: [Vec<u32>; 2],
    start: [Vec<u32>; 2],
    parts: Vec<Part>,
    stamp: [Vec<u32>; 2],
    owner: [Vec<u32>; 2],
    generation: u32,
    buf: Vec<(u32, u32, u128)>,
    /// Target cells of the enclosing branching calls (the `Traces` selector).
    ancestors: Vec<Vec<u32>>,
}

/// A label `[a, b, ...]` as one integer whose order is the list order: element
/// `i` plus one in the 16-bit slot `i` from the top, so a proper prefix (zero
/// in the next slot) comes first.
fn encode(list: &[u64]) -> Option<u128> {
    if list.len() > 8 {
        return None;
    }
    let mut v = 0u128;
    for (i, &x) in list.iter().enumerate() {
        if x + 1 >= 1 << 16 {
            return None;
        }
        v |= u128::from(x + 1) << (112 - 16 * i);
    }
    Some(v)
}

impl<'a> Engine<'a> {
    fn new(input: &'a Input, options: Options) -> Result<Self, Refusal> {
        let n = input.nodes();
        let m = input.lines.len();
        let mut node_adj = vec![Vec::new(); n];
        let mut line_off = Vec::with_capacity(m + 1);
        let mut line_adj = Vec::new();
        let mut line_rep = Vec::new();
        line_off.push(0);
        for (l, line) in input.lines.iter().enumerate() {
            for u in line.nodes() {
                node_adj[u as usize].push((l as u32, line_adj.len() as u32));
                line_adj.push(u);
                line_rep.push(line.occ.iter().filter(|&&w| w == u).count() as u32);
            }
            line_off.push(line_adj.len() as u32);
        }
        let mut keyed: Vec<(Vec<u8>, u64, u32)> = (0..m)
            .map(|l| (input.plain_masked(l), input.lines[l].count, l as u32))
            .collect();
        keyed.sort_unstable();
        let mut rank = vec![0u32; m];
        let mut r = 0u32;
        for (i, k) in keyed.iter().enumerate() {
            if i > 0 && (k.0 != keyed[i - 1].0 || k.1 != keyed[i - 1].1) {
                r += 1;
            }
            rank[k.2 as usize] = r;
        }
        let mut engine = Self {
            input,
            options,
            stats: Stats {
                nodes: n as u64,
                lines: m as u64,
                ..Stats::default()
            },
            node_lines: input.node_lines(),
            node_adj,
            line_lab: vec![0; line_adj.len()],
            line_off,
            line_adj,
            line_rep,
            rank,
            free: vec![true; n],
            pos: vec![0; n],
            fixed_log: Vec::new(),
            at: [vec![0; n], vec![0; m]],
            start: [vec![0; n], vec![0; m]],
            parts: Vec::new(),
            stamp: [vec![0; n], vec![0; m]],
            owner: [vec![0; n], vec![0; m]],
            generation: 0,
            buf: Vec::new(),
            ancestors: Vec::new(),
        };
        for l in 0..m {
            engine.relabel(l).ok_or(Refusal::Width)?;
        }
        Ok(engine)
    }

    /// Recompute the labels of the incidences of line `l` from `free`.
    fn relabel(&mut self, l: usize) -> Option<()> {
        let occ = &self.input.lines[l].occ;
        for slot in self.line_off[l] as usize..self.line_off[l + 1] as usize {
            let u = self.line_adj[slot];
            let mut list: Vec<u64> = Vec::with_capacity(2);
            let mut k = 0u64;
            for &w in occ {
                if self.free[w as usize] {
                    if w == u {
                        list.push(k);
                    }
                    k += 1;
                }
            }
            self.line_lab[slot] = encode(&list)?;
        }
        Some(())
    }

    fn fix(&mut self, nodes: &[u32], p: u64) -> Result<(), Refusal> {
        for (i, &u) in nodes.iter().enumerate() {
            self.free[u as usize] = false;
            self.pos[u as usize] = p.checked_add(i as u64).ok_or(Refusal::Width)?;
            self.fixed_log.push(u);
        }
        for &u in nodes {
            for k in 0..self.node_lines[u as usize].len() {
                let l = self.node_lines[u as usize][k] as usize;
                self.relabel(l).expect("labels only shrink after the first");
            }
        }
        Ok(())
    }

    fn unfix_to(&mut self, mark: usize) {
        while self.fixed_log.len() > mark {
            let u = self.fixed_log.pop().expect("a fixed node");
            self.free[u as usize] = true;
            for k in 0..self.node_lines[u as usize].len() {
                let l = self.node_lines[u as usize][k] as usize;
                self.relabel(l).expect("labels were valid before");
            }
        }
    }

    fn check(&self) -> Result<(), Refusal> {
        if self.stats.units() > self.options.limit {
            return Err(Refusal::Limit(Box::new(self.stats.clone())));
        }
        Ok(())
    }

    // ---- partition operations -------------------------------------------

    /// A new partition of the given cells (each a list of vertices), in order.
    fn new_part(&mut self, cells: [Vec<Vec<u32>>; 2]) -> usize {
        let mut part = Part::default();
        for (s, side) in cells.into_iter().enumerate() {
            for cell in side {
                let c = part.elems[s].len() as u32;
                let l = cell.len() as u32;
                for v in cell {
                    self.at[s][v as usize] = part.elems[s].len() as u32;
                    self.start[s][v as usize] = c;
                    part.elems[s].push(v);
                    part.len[s].push(0);
                    part.cap[s].push(0);
                }
                part.len[s][c as usize] = l;
                part.cap[s][c as usize] = l;
                part.live[s] += l;
            }
        }
        self.parts.push(part);
        self.parts.len() - 1
    }

    fn undo_to(&mut self, pi: usize, mark: usize) {
        while self.parts[pi].trail.len() > mark {
            let rec = self.parts[pi].trail.pop().expect("a record");
            let part = &mut self.parts[pi];
            match rec {
                Undo::Split {
                    s,
                    c,
                    old_len,
                    old_cap,
                    first_len,
                } => {
                    let s = s as usize;
                    for q in (c + first_len)..(c + old_len) {
                        let v = part.elems[s][q as usize];
                        self.start[s][v as usize] = c;
                    }
                    part.len[s][c as usize] = old_len;
                    part.cap[s][c as usize] = old_cap;
                }
                Undo::Delete { s, v, c } => {
                    let s = s as usize;
                    let q = c + part.len[s][c as usize];
                    debug_assert_eq!(part.elems[s][q as usize], v);
                    part.len[s][c as usize] += 1;
                    part.live[s] += 1;
                    self.at[s][v as usize] = q;
                    self.start[s][v as usize] = c;
                }
            }
        }
    }

    /// Remove `v` from its cell (it becomes a dead slot at the cell's end).
    fn delete(&mut self, pi: usize, s: usize, v: u32) {
        let c = self.start[s][v as usize];
        let part = &mut self.parts[pi];
        let last = c + part.len[s][c as usize] - 1;
        let q = self.at[s][v as usize];
        let w = part.elems[s][last as usize];
        part.elems[s].swap(q as usize, last as usize);
        self.at[s][w as usize] = q;
        self.at[s][v as usize] = last;
        part.len[s][c as usize] -= 1;
        part.live[s] -= 1;
        part.trail.push(Undo::Delete { s: s as u8, v, c });
        self.stats.trail += 1;
    }

    /// Replace the cell at `c` (side `s`) by `fragments` in order, the first
    /// keeping `c`; the queue rule (5.4) when `queue` is given.
    fn split(
        &mut self,
        pi: usize,
        s: usize,
        c: u32,
        fragments: &[&[u32]],
        queue: Option<&mut BTreeSet<(u8, u32)>>,
    ) {
        let part = &mut self.parts[pi];
        let old_len = part.len[s][c as usize];
        let old_cap = part.cap[s][c as usize];
        let mut q = c;
        for f in fragments {
            for &v in *f {
                // Place v at q: swap with whatever is there.
                let from = self.at[s][v as usize];
                let w = part.elems[s][q as usize];
                part.elems[s].swap(from as usize, q as usize);
                self.at[s][w as usize] = from;
                self.at[s][v as usize] = q;
                q += 1;
            }
        }
        let mut colour = c;
        let k = fragments.len();
        let largest = (0..k)
            .max_by(|&a, &b| fragments[a].len().cmp(&fragments[b].len()).then(b.cmp(&a)))
            .expect("fragments");
        let was_queued = queue.as_ref().is_some_and(|q| q.contains(&(s as u8, c)));
        let mut queue = queue;
        for (i, f) in fragments.iter().enumerate() {
            let l = f.len() as u32;
            for &v in *f {
                self.start[s][v as usize] = colour;
            }
            part.len[s][colour as usize] = l;
            part.cap[s][colour as usize] = if i + 1 == k {
                l + (old_cap - old_len)
            } else {
                l
            };
            if let Some(queue) = queue.as_deref_mut()
                && (was_queued || i != largest)
            {
                queue.insert((s as u8, colour));
            }
            colour += l;
        }
        part.trail.push(Undo::Split {
            s: s as u8,
            c,
            old_len,
            old_cap,
            first_len: fragments[0].len() as u32,
        });
        self.stats.trail += 1;
    }

    /// REFINE (5.5) of partition `pi` from `queue`.
    fn refine(&mut self, pi: usize, queue: &mut BTreeSet<(u8, u32)>) -> Result<(), Refusal> {
        while let Some((s, c)) = queue.pop_first() {
            self.stats.pops += 1;
            let s = s as usize;
            let other = 1 - s;
            self.buf.clear();
            let l = self.parts[pi].len[s][c as usize];
            for q in c..c + l {
                let w = self.parts[pi].elems[s][q as usize];
                if s == 0 {
                    for &(line, slot) in &self.node_adj[w as usize] {
                        self.stats.visits += 1;
                        self.stats.visit_elements += u64::from(self.line_rep[slot as usize]);
                        let x = self.start[1][line as usize];
                        if self.parts[pi].len[1][x as usize] > 1 {
                            self.buf.push((x, line, self.line_lab[slot as usize]));
                        }
                    }
                } else {
                    let w = w as usize;
                    for slot in self.line_off[w]..self.line_off[w + 1] {
                        let u = self.line_adj[slot as usize];
                        if !self.free[u as usize] {
                            continue;
                        }
                        self.stats.visits += 1;
                        self.stats.visit_elements += u64::from(self.line_rep[slot as usize]);
                        let x = self.start[0][u as usize];
                        if self.parts[pi].len[0][x as usize] > 1 {
                            self.buf.push((x, u, self.line_lab[slot as usize]));
                        }
                    }
                }
            }
            self.check()?;
            if self.buf.is_empty() {
                continue;
            }
            let mut buf = std::mem::take(&mut self.buf);
            buf.sort_unstable();
            // Per touched vertex its key, a slice of `buf`.
            let mut i = 0;
            while i < buf.len() {
                let x = buf[i].0;
                let mut j = i;
                // Touched vertices of cell x: (vertex, key range).
                let mut touched: Vec<(u32, usize, usize)> = Vec::new();
                while j < buf.len() && buf[j].0 == x {
                    let y = buf[j].1;
                    let a = j;
                    while j < buf.len() && buf[j].0 == x && buf[j].1 == y {
                        j += 1;
                    }
                    touched.push((y, a, j));
                }
                i = j;
                let len_x = self.parts[pi].len[other][x as usize];
                let untouched = len_x as usize - touched.len();
                let key = |t: &(u32, usize, usize)| buf[t.1..t.2].iter().map(|e| e.2);
                let mut compares = 0u64;
                touched.sort_unstable_by(|a, b| {
                    compares += 1;
                    key(a).cmp(key(b))
                });
                self.stats.key_compares += compares;
                // Group boundaries.
                let mut groups: Vec<(usize, usize)> = Vec::new();
                let mut g = 0;
                for k in 1..=touched.len() {
                    if k == touched.len() || key(&touched[k]).ne(key(&touched[k - 1])) {
                        groups.push((g, k));
                        g = k;
                    }
                }
                if untouched == 0 && groups.len() == 1 {
                    continue;
                }
                // The untouched members, in place.
                let start_x = x;
                let mut members: Vec<u32> = Vec::with_capacity(len_x as usize);
                {
                    let part = &self.parts[pi];
                    members.extend_from_slice(
                        &part.elems[other][start_x as usize..(start_x + len_x) as usize],
                    );
                }
                let mut is_touched: FastMap<u32, ()> = FastMap::default();
                for t in &touched {
                    is_touched.insert(t.0, ());
                }
                let rest: Vec<u32> = if untouched > 0 {
                    members
                        .iter()
                        .copied()
                        .filter(|v| !is_touched.contains_key(v))
                        .collect()
                } else {
                    Vec::new()
                };
                let sorted: Vec<u32> = touched.iter().map(|t| t.0).collect();
                let mut frags: Vec<&[u32]> = Vec::with_capacity(groups.len() + 1);
                if untouched > 0 {
                    frags.push(&rest);
                }
                for &(a, b) in &groups {
                    frags.push(&sorted[a..b]);
                }
                self.split(pi, other, start_x, &frags, Some(queue));
            }
            self.buf = buf;
        }
        Ok(())
    }

    /// INDIVIDUALISATION (5.8) of `v` in the node cell at `c`; returns the queue.
    fn individualise(&mut self, pi: usize, c: u32, v: u32) -> BTreeSet<(u8, u32)> {
        let l = self.parts[pi].len[0][c as usize];
        let rest: Vec<u32> = self.parts[pi].elems[0][c as usize..(c + l) as usize]
            .iter()
            .copied()
            .filter(|&x| x != v)
            .collect();
        let mut queue = BTreeSet::new();
        self.split(pi, 0, c, &[&[v], &rest], Some(&mut queue));
        queue
    }

    // ---- FIX, entries, restriction --------------------------------------

    /// The singleton node cells of a partition in colour order.
    fn singletons(&self, pi: usize) -> (Vec<u32>, bool) {
        let part = &self.parts[pi];
        let mut fixed = Vec::new();
        let mut any_big = false;
        for (c, l) in part.cells(0) {
            if l == 1 {
                fixed.push(part.elems[0][c as usize]);
            } else {
                any_big = true;
            }
        }
        (fixed, any_big)
    }

    /// Fix `fixed` at `p..` and form the entries of the lines it completes.
    fn fix_and_entries(
        &mut self,
        fixed: &[u32],
        p: u64,
    ) -> Result<(Vec<u32>, Vec<Entry>), Refusal> {
        self.fix(fixed, p)?;
        self.generation += 1;
        let g = self.generation;
        let mut e_lines = Vec::new();
        for &u in fixed {
            for &l in &self.node_lines[u as usize] {
                if self.stamp[1][l as usize] == g {
                    continue;
                }
                self.stamp[1][l as usize] = g;
                let line = &self.input.lines[l as usize];
                if line.occ.iter().all(|&w| !self.free[w as usize]) {
                    e_lines.push(l);
                }
            }
        }
        let mut e: Vec<Entry> = e_lines
            .iter()
            .map(|&l| entry(&self.input.lines[l as usize], &self.pos))
            .collect();
        self.stats.entries_formed += formed_cost(&e);
        e.sort_unstable();
        Ok((e_lines, e))
    }

    /// Delete the removed vertices, discover the free components of the
    /// remainder and restrict; returns the partitions of the components.
    fn remove_and_discover(&mut self, pi: usize, fixed: &[u32], e_lines: &[u32]) -> Vec<usize> {
        for &u in fixed {
            self.delete(pi, 0, u);
        }
        for &l in e_lines {
            self.delete(pi, 1, l);
        }
        let incidences: usize = fixed
            .iter()
            .map(|&u| self.node_lines[u as usize].len())
            .sum();
        self.stats.restriction += (fixed.len() + e_lines.len() + incidences) as u64;
        let total = u64::from(self.parts[pi].live[0] + self.parts[pi].live[1]);
        if total == 0 {
            return Vec::new();
        }
        // Start lines: live lines of the fixed nodes.
        self.generation += 1;
        let g = self.generation;
        let mut searches: Vec<Search> = Vec::new();
        let mut parent: Vec<u32> = Vec::new();
        for &u in fixed {
            for &l in &self.node_lines[u as usize] {
                if self.stamp[1][l as usize] == g || !self.line_has_free(l) {
                    continue;
                }
                self.stamp[1][l as usize] = g;
                self.owner[1][l as usize] = searches.len() as u32;
                parent.push(searches.len() as u32);
                let mut search = Search::default();
                search.queue.push_back((1, l));
                search.members[1].push(l);
                searches.push(search);
            }
        }
        let stop_at =
            usize::from(self.options.has(Flag::Incremental) && self.options.has(Flag::Lazy));
        let find = |parent: &mut Vec<u32>, x: u32| -> u32 {
            let mut r = x;
            while parent[r as usize] != r {
                r = parent[r as usize];
            }
            let mut y = x;
            while parent[y as usize] != r {
                let n = parent[y as usize];
                parent[y as usize] = r;
                y = n;
            }
            r
        };
        let mut active: Vec<u32> = (0..searches.len() as u32).collect();
        while active.len() > stop_at {
            let mut k = 0;
            while k < active.len() {
                let r = find(&mut parent, active[k]);
                if r != active[k] || searches[r as usize].queue.is_empty() {
                    active.swap_remove(k);
                    continue;
                }
                let (side, v) = searches[r as usize]
                    .queue
                    .pop_front()
                    .expect("a pending vertex");
                self.stats.discovery_steps += 1;
                let neighbours: Vec<(u8, u32)> = if side == 1 {
                    let v = v as usize;
                    (self.line_off[v]..self.line_off[v + 1])
                        .map(|slot| self.line_adj[slot as usize])
                        .filter(|&u| self.free[u as usize])
                        .map(|u| (0, u))
                        .collect()
                } else {
                    self.node_lines[v as usize]
                        .iter()
                        .map(|&l| (1, l))
                        .collect()
                };
                let mut cur = r;
                for (ys, y) in neighbours {
                    self.stats.discovery_steps += 1;
                    let ysz = ys as usize;
                    if self.stamp[ysz][y as usize] == g {
                        let o = find(&mut parent, self.owner[ysz][y as usize]);
                        if o != cur {
                            // Merge the smaller search into the larger.
                            let size = |s: &Search| s.members[0].len() + s.members[1].len();
                            let (big, small) =
                                if size(&searches[o as usize]) > size(&searches[cur as usize]) {
                                    (o, cur)
                                } else {
                                    (cur, o)
                                };
                            let moved = std::mem::take(&mut searches[small as usize]);
                            let target = &mut searches[big as usize];
                            target.queue.extend(moved.queue);
                            let [m0, m1] = moved.members;
                            target.members[0].extend(m0);
                            target.members[1].extend(m1);
                            parent[small as usize] = big;
                            cur = big;
                            active.push(big);
                        }
                        continue;
                    }
                    self.stamp[ysz][y as usize] = g;
                    self.owner[ysz][y as usize] = cur;
                    let target = &mut searches[cur as usize];
                    target.queue.push_back((ys, y));
                    target.members[ysz].push(y);
                }
                k += 1;
            }
            active.sort_unstable();
            active.dedup();
            active.retain(|&a| parent[a as usize] == a && !searches[a as usize].queue.is_empty());
        }
        // Finished components, and at most one unfinished.
        let mut done: Vec<usize> = Vec::new();
        let mut open: Option<usize> = None;
        for (i, s) in searches.iter().enumerate() {
            if parent[i] != i as u32 {
                continue;
            }
            if s.queue.is_empty() {
                done.push(i);
            } else {
                open = Some(i);
            }
        }
        let size = |s: &Search| (s.members[0].len() + s.members[1].len()) as u64;
        let mut sizes: Vec<u64> = done.iter().map(|&i| size(&searches[i])).collect();
        if open.is_some() {
            sizes.push(total - sizes.iter().sum::<u64>());
        }
        if sizes.len() >= 2 {
            let largest = *sizes.iter().max().expect("sizes");
            self.stats.restriction += sizes.iter().sum::<u64>() - largest;
        }
        // Which component stays in place.
        let keep: Option<usize> = if !self.options.has(Flag::Lazy) {
            None
        } else if open.is_some() {
            open
        } else {
            done.iter()
                .copied()
                .max_by(|&a, &b| size(&searches[a]).cmp(&size(&searches[b])).then(b.cmp(&a)))
        };
        let mut out = Vec::with_capacity(done.len() + 1);
        for &i in &done {
            if Some(i) == keep {
                continue;
            }
            let members = std::mem::take(&mut searches[i].members);
            out.push(self.copy_out(pi, &members));
        }
        if keep.is_some() {
            out.push(pi);
        }
        out
    }

    fn line_has_free(&self, l: u32) -> bool {
        self.input.lines[l as usize]
            .occ
            .iter()
            .any(|&u| self.free[u as usize])
    }

    /// Copy one component out of partition `pi` into a new partition, cells and
    /// their order kept, and delete it from `pi`.
    fn copy_out(&mut self, pi: usize, members: &[Vec<u32>; 2]) -> usize {
        let mut cells: [Vec<Vec<u32>>; 2] = [Vec::new(), Vec::new()];
        for (s, list) in members.iter().enumerate() {
            let mut keyed: Vec<(u32, u32)> = list
                .iter()
                .map(|&v| (self.start[s][v as usize], v))
                .collect();
            keyed.sort_unstable();
            for (i, &(c, v)) in keyed.iter().enumerate() {
                if i == 0 || c != keyed[i - 1].0 {
                    cells[s].push(Vec::new());
                }
                cells[s].last_mut().expect("a cell").push(v);
            }
            self.stats.copied += list.len() as u64;
        }
        for (s, list) in members.iter().enumerate() {
            for &v in list {
                self.delete(pi, s, v);
            }
        }
        self.new_part(cells)
    }

    // ---- the search -----------------------------------------------------

    /// Begin a FIX and NEST on partition `pi`: fix its singletons, form `E`,
    /// restrict to the free components. Returns the nest.
    fn begin_nest(
        &mut self,
        pi: usize,
        p: u64,
        depth: u64,
        fixed: Vec<u32>,
    ) -> Result<Nest, Refusal> {
        let arena_mark = self.parts.len();
        let (e_lines, e) = self.fix_and_entries(&fixed, p)?;
        let comps = self.remove_and_discover(pi, &fixed, &e_lines);
        self.check()?;
        Ok(Nest {
            p,
            fixed,
            e,
            comps,
            next: 0,
            done: Vec::new(),
            arena_mark,
            depth,
        })
    }

    /// The target cell of a partition with no singleton node cell.
    fn target(&self, pi: usize) -> (u32, Vec<u32>) {
        let part = &self.parts[pi];
        let cells = part.cells(0);
        let members: Vec<&[u32]> = cells
            .iter()
            .map(|&(c, l)| &part.elems[0][c as usize..(c + l) as usize])
            .collect();
        let i = pick_target(self.options.selector, &members, &self.ancestors);
        let (c, l) = cells[i];
        (c, part.elems[0][c as usize..(c + l) as usize].to_vec())
    }

    /// The smallest `E` of a nested call: its own after its fixing, or the
    /// smallest over its children (10.2). Leaves everything as it found it.
    fn head(&mut self, pi: usize, p: u64) -> Result<Vec<Entry>, Refusal> {
        let (fixed, any_big) = self.singletons(pi);
        if !fixed.is_empty() || !any_big {
            let mark = self.fixed_log.len();
            let (_, e) = self.fix_and_entries(&fixed, p)?;
            self.unfix_to(mark);
            return Ok(e);
        }
        let (c, target) = self.target(pi);
        let mut best: Option<Vec<Entry>> = None;
        for v in target {
            self.stats.children += 1;
            let mark = self.parts[pi].trail.len();
            let fmark = self.fixed_log.len();
            let mut queue = self.individualise(pi, c, v);
            self.refine(pi, &mut queue)?;
            let (fixed, _) = self.singletons(pi);
            let (_, e) = self.fix_and_entries(&fixed, p)?;
            self.unfix_to(fmark);
            self.undo_to(pi, mark);
            if best.as_ref().is_none_or(|b| {
                cmp_entries(&e, b, &mut self.stats.entries_compared) == Ordering::Less
            }) {
                best = Some(e);
            }
        }
        Ok(best.expect("a child"))
    }

    /// The ordered cell sizes of both sides (the experimental invariant).
    fn invariant(&self, pi: usize) -> Vec<u32> {
        let part = &self.parts[pi];
        let mut out: Vec<u32> = part.cells(0).iter().map(|c| c.1).collect();
        out.push(0);
        out.extend(part.cells(1).iter().map(|c| c.1));
        out
    }

    /// Run one call to its certificate, iteratively.
    fn run_call(&mut self, pi: usize, p: u64) -> Result<Chosen, Refusal> {
        let mut stack: Vec<Frame> = vec![Frame::Call { pi, p, depth: 0 }];
        let mut ret: Option<Chosen> = None;
        while let Some(frame) = stack.pop() {
            match frame {
                Frame::Call { pi, p, depth } => {
                    self.stats.calls += 1;
                    self.stats.max_depth = self.stats.max_depth.max(depth);
                    let (mut fixed, mut any_big) = self.singletons(pi);
                    if self.options.has(Flag::Wl2) && fixed.is_empty() && any_big {
                        self.apply_wl2(pi)?;
                        (fixed, any_big) = self.singletons(pi);
                    }
                    if !any_big {
                        self.stats.leaves += 1;
                    }
                    if !fixed.is_empty() {
                        let nest = self.begin_nest(pi, p, depth, fixed)?;
                        stack.push(Frame::Nest(Box::new(nest)));
                        continue;
                    }
                    self.stats.branch_calls += 1;
                    self.stats.branch_nodes += u64::from(self.parts[pi].live[0]);
                    let (c, target) = self.target(pi);
                    self.stats.largest_target = self.stats.largest_target.max(target.len() as u64);
                    self.ancestors.push(target.clone());
                    let mut twins = Uf::default();
                    if self.options.has(Flag::Twins) {
                        self.twin_classes(&target, &mut twins);
                    }
                    stack.push(Frame::Branch(Box::new(Branch {
                        pi,
                        p,
                        depth,
                        c,
                        target,
                        next: 0,
                        best: None,
                        cur_inv: Vec::new(),
                        tried: Vec::new(),
                        orbits: Uf::default(),
                        twins,
                        marks: (0, 0, 0),
                    })));
                }
                Frame::Nest(mut nest) => {
                    if let Some(r) = ret.take() {
                        nest.done.push(r);
                    }
                    if nest.next < nest.comps.len() {
                        let ci = nest.comps[nest.next];
                        nest.next += 1;
                        let p2 = nest.p + nest.fixed.len() as u64;
                        let depth = nest.depth + 1;
                        stack.push(Frame::Nest(nest));
                        stack.push(Frame::Call {
                            pi: ci,
                            p: p2,
                            depth,
                        });
                        continue;
                    }
                    let mut compared = 0u64;
                    nest.done
                        .sort_by(|a, b| cmp_cert(&a.cert, &b.cert, &mut compared));
                    self.stats.entries_compared += compared;
                    if nest.done.windows(2).any(|w| w[0].cert == w[1].cert) {
                        self.stats.equal_certificates += 1;
                    }
                    self.parts.truncate(nest.arena_mark);
                    let nest = *nest;
                    let size =
                        nest.fixed.len() as u64 + nest.done.iter().map(|n| n.size).sum::<u64>();
                    let cert = Arc::new(Cert {
                        e: nest.e,
                        c: nest.done.iter().map(|n| Arc::clone(&n.cert)).collect(),
                    });
                    ret = Some(Chosen {
                        cert,
                        fixed: nest.fixed,
                        nested: nest.done,
                        size,
                    });
                }
                Frame::Branch(mut b) => {
                    if let Some(r) = ret.take() {
                        let generators = self.child_done(&mut b, r);
                        self.close_child(&b);
                        for &(x, y) in &generators {
                            b.orbits.union(x, y);
                        }
                        if !generators.is_empty() {
                            for f in &mut stack {
                                if let Frame::Branch(a) = f {
                                    for &(x, y) in &generators {
                                        a.orbits.union(x, y);
                                    }
                                }
                            }
                        }
                    }
                    // Next candidate, orbit- and twin-pruned.
                    let mut chosen = None;
                    while b.next < b.target.len() {
                        let v = b.target[b.next];
                        b.next += 1;
                        if self.options.has(Flag::Twins) {
                            let rv = b.twins.find(v);
                            let tried = b.tried.clone();
                            if tried.iter().any(|&t| b.twins.find(t) == rv) {
                                self.stats.pruned_twin += 1;
                                continue;
                            }
                        }
                        if self.options.has(Flag::Orbits) {
                            let rv = b.orbits.find(v);
                            let tried = b.tried.clone();
                            if tried.iter().any(|&t| b.orbits.find(t) == rv) {
                                self.stats.pruned_orbit += 1;
                                continue;
                            }
                        }
                        chosen = Some(v);
                        break;
                    }
                    let Some(v) = chosen else {
                        self.ancestors.pop();
                        ret = Some(b.best.take().expect("a child").1);
                        continue;
                    };
                    b.tried.push(v);
                    self.stats.children += 1;
                    b.marks = (
                        self.parts[b.pi].trail.len(),
                        self.fixed_log.len(),
                        self.parts.len(),
                    );
                    let mut queue = self.individualise(b.pi, b.c, v);
                    self.refine(b.pi, &mut queue)?;
                    if self.options.has(Flag::Invariant) {
                        b.cur_inv = self.invariant(b.pi);
                        self.stats.invariant += b.cur_inv.len() as u64 - 1;
                        if let Some((inv, _)) = &b.best {
                            match cmp_invariant(&b.cur_inv, inv, &mut self.stats.invariant) {
                                Ordering::Greater => {
                                    self.stats.pruned_invariant += 1;
                                    self.close_child(&b);
                                    stack.push(Frame::Branch(b));
                                    continue;
                                }
                                Ordering::Less => b.best = None,
                                Ordering::Equal => {}
                            }
                        }
                    }
                    let (fixed, _) = self.singletons(b.pi);
                    let arena_mark = self.parts.len();
                    let (e_lines, e) = self.fix_and_entries(&fixed, b.p)?;
                    let mut prune = false;
                    let mut e_equal = false;
                    if self.options.has(Flag::PruneE)
                        && let Some((_, best)) = &b.best
                    {
                        match cmp_entries(&e, &best.cert.e, &mut self.stats.entries_compared) {
                            Ordering::Greater => {
                                self.stats.pruned_e += 1;
                                prune = true;
                            }
                            Ordering::Equal => e_equal = true,
                            Ordering::Less => {}
                        }
                    }
                    let comps = if prune {
                        Vec::new()
                    } else {
                        self.remove_and_discover(b.pi, &fixed, &e_lines)
                    };
                    if !prune
                        && e_equal
                        && self.options.has(Flag::PruneNestedE)
                        && !self.options.has(Flag::Wl2)
                    {
                        let p2 = b.p + fixed.len() as u64;
                        let mut least: Option<Vec<Entry>> = None;
                        for &ci in &comps {
                            let h = self.head(ci, p2)?;
                            if least.as_ref().is_none_or(|l| {
                                cmp_entries(&h, l, &mut self.stats.entries_compared)
                                    == Ordering::Less
                            }) {
                                least = Some(h);
                            }
                        }
                        let best_least = b
                            .best
                            .as_ref()
                            .and_then(|(_, c)| c.cert.c.first().map(|c| &c.e));
                        let order = match (&least, best_least) {
                            (None, None) => Ordering::Equal,
                            (None, Some(_)) => Ordering::Less,
                            (Some(_), None) => Ordering::Greater,
                            (Some(a), Some(b)) => {
                                cmp_entries(a, b, &mut self.stats.entries_compared)
                            }
                        };
                        if order == Ordering::Greater {
                            self.stats.pruned_nested_e += 1;
                            prune = true;
                        }
                    }
                    self.check()?;
                    if prune {
                        self.parts.truncate(arena_mark);
                        self.close_child(&b);
                        stack.push(Frame::Branch(b));
                        continue;
                    }
                    let nest = Nest {
                        p: b.p,
                        fixed,
                        e,
                        comps,
                        next: 0,
                        done: Vec::new(),
                        arena_mark,
                        depth: b.depth,
                    };
                    stack.push(Frame::Branch(b));
                    stack.push(Frame::Nest(Box::new(nest)));
                }
            }
        }
        Ok(ret.expect("the call's result"))
    }

    /// Undo a child of a branching call.
    fn close_child(&mut self, b: &Branch) {
        self.undo_to(b.pi, b.marks.0);
        self.unfix_to(b.marks.1);
        self.parts.truncate(b.marks.2);
    }

    /// A child finished: keep the smaller; on a tie, the automorphism between
    /// the two (pairs of nodes at equal final positions within the call).
    fn child_done(&mut self, b: &mut Branch, r: Chosen) -> Vec<(u32, u32)> {
        let inv = std::mem::take(&mut b.cur_inv);
        let Some((best_inv, best)) = &b.best else {
            b.best = Some((inv, r));
            return Vec::new();
        };
        let mut compared = 0u64;
        let order = inv
            .cmp(best_inv)
            .then_with(|| cmp_cert(&r.cert, &best.cert, &mut compared));
        // The invariants were compared (and charged) before this child's fixing.
        self.stats.entries_compared += compared;
        match order {
            Ordering::Less => {
                b.best = Some((inv, r));
                Vec::new()
            }
            Ordering::Greater => Vec::new(),
            Ordering::Equal => {
                self.stats.equal_certificates += 1;
                let mut pa = relative(best);
                let mut pb = relative(&r);
                pa.sort_unstable_by_key(|x| x.1);
                pb.sort_unstable_by_key(|x| x.1);
                let pairs: Vec<(u32, u32)> = pa
                    .iter()
                    .zip(&pb)
                    .filter(|(a, b)| a.0 != b.0)
                    .map(|(a, b)| (a.0, b.0))
                    .collect();
                if !pairs.is_empty() {
                    self.stats.generators += 1;
                }
                pairs
            }
        }
    }

    /// Twin classes of the target cell (10.3): equal sorted lists of
    /// `(rank, line nodes with self replaced)`.
    fn twin_classes(&self, target: &[u32], uf: &mut Uf) {
        let mut sigs: Vec<(TwinSignature, u32)> = target
            .iter()
            .map(|&u| {
                let mut sig: Vec<(u32, Vec<u32>)> = self.node_lines[u as usize]
                    .iter()
                    .map(|&l| {
                        let occ = self.input.lines[l as usize]
                            .occ
                            .iter()
                            .map(|&w| if w == u { u32::MAX } else { w })
                            .collect();
                        (self.rank[l as usize], occ)
                    })
                    .collect();
                sig.sort_unstable();
                (sig, u)
            })
            .collect();
        sigs.sort_unstable();
        for w in sigs.windows(2) {
            if w[0].0 == w[1].0 {
                uf.union(w[0].1, w[1].1);
            }
        }
    }

    /// Experiment: split the node cells by two-dimensional refinement, then
    /// REFINE with every cell queued.
    fn apply_wl2(&mut self, pi: usize) -> Result<(), Refusal> {
        let view: [Vec<Vec<u32>>; 2] = [0, 1].map(|s| {
            self.parts[pi]
                .cells(s)
                .iter()
                .map(|&(c, l)| self.parts[pi].elems[s][c as usize..(c + l) as usize].to_vec())
                .collect()
        });
        let refined = super::wl2::refine_nodes(self.input, &self.free, &view, &mut self.stats);
        // Apply as splits of each old cell.
        let mut k = 0;
        for cell in &view[0] {
            let c = self.start[0][cell[0] as usize];
            let mut frags: Vec<Vec<u32>> = Vec::new();
            let mut count = 0;
            while count < cell.len() {
                count += refined[k].len();
                frags.push(refined[k].clone());
                k += 1;
            }
            if frags.len() > 1 {
                let refs: Vec<&[u32]> = frags.iter().map(Vec::as_slice).collect();
                self.split(pi, 0, c, &refs, None);
            }
        }
        let mut queue = BTreeSet::new();
        for s in 0..2u8 {
            for (c, _) in self.parts[pi].cells(s as usize) {
                queue.insert((s, c));
            }
        }
        self.refine(pi, &mut queue)
    }
}

/// Final positions within one call, relative to its own offset 0.
fn relative(chosen: &Chosen) -> Vec<(u32, u64)> {
    let mut out = Vec::with_capacity(chosen.size as usize);
    let mut stack: Vec<(&Chosen, u64)> = vec![(chosen, 0)];
    while let Some((call, o)) = stack.pop() {
        for (i, &node) in call.fixed.iter().enumerate() {
            out.push((node, o + i as u64));
        }
        let mut next = o + call.fixed.len() as u64;
        for nested in &call.nested {
            stack.push((nested, next));
            next += nested.size;
        }
    }
    out
}

/// Label `input` with every permitted shortcut the options enable.
pub(crate) fn label_input(input: &Input, options: Options) -> Result<Labelled, Refusal> {
    let mut engine = Engine::new(input, options)?;
    let n = input.nodes();
    let all: Vec<u32> = (0..n as u32).collect();
    let comps = components(
        input,
        &engine.node_lines,
        &all,
        &engine.free,
        &mut engine.stats.discovery_steps,
    );
    engine.stats.top_components = comps.len() as u64;
    if comps.len() >= 2 {
        let sizes: Vec<u64> = comps
            .iter()
            .map(|(a, b)| (a.len() + b.len()) as u64)
            .collect();
        engine.stats.restriction +=
            sizes.iter().sum::<u64>() - sizes.iter().max().expect("two components");
    }
    let mut tops: Vec<Chosen> = Vec::with_capacity(comps.len());
    for (cn, cl) in comps {
        engine.stats.start += start_cost(input, &cl);
        let mut lines = cl;
        lines.sort_unstable_by_key(|&l| (engine.rank[l as usize], l));
        let mut line_cells: Vec<Vec<u32>> = Vec::new();
        for (i, &l) in lines.iter().enumerate() {
            if i == 0 || engine.rank[l as usize] != engine.rank[lines[i - 1] as usize] {
                line_cells.push(Vec::new());
            }
            line_cells.last_mut().expect("a cell").push(l);
        }
        let pi = engine.new_part([vec![cn], line_cells]);
        let mut queue = BTreeSet::new();
        for s in 0..2u8 {
            for (c, _) in engine.parts[pi].cells(s as usize) {
                queue.insert((s, c));
            }
        }
        engine.refine(pi, &mut queue)?;
        tops.push(engine.run_call(pi, 0)?);
        engine.parts.clear();
    }
    let mut compared = 0u64;
    tops.sort_by(|a, b| cmp_cert(&a.cert, &b.cert, &mut compared));
    engine.stats.entries_compared += compared;
    if tops.windows(2).any(|w| w[0].cert == w[1].cert) {
        engine.stats.equal_certificates += 1;
    }
    engine.check()?;
    let mut positions = vec![0u64; n];
    let mut o = 0u64;
    for t in &tops {
        t.assign(o, &mut positions);
        o += t.size;
    }
    Ok(Labelled {
        document: document(input, &positions),
        positions,
        tops: tops.iter().map(|t| Arc::clone(&t.cert)).collect(),
        stats: engine.stats,
    })
}
