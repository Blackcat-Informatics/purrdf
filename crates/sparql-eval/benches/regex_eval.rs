// not asked of their items.
#![allow(missing_docs)]

//! Per-row cost of SPARQL `REGEX`/`REPLACE` after the shared XSD/XPath
//! translation was inserted in front of `purrdf_core::xsd_regex::compile`.
//!
//! [`query_eval::b_scan_filter`](../query_eval/index.html) runs one constant
//! `REGEX` as part of a mixed whole-query benchmark. This target isolates the
//! row loop that actually matters for a filter and separates the two regimes
//! `EvalCtx::regex_cache` distinguishes:
//!
//! * `regex_constant` — a literal pattern argument. The per-query cache must
//!   compile it **once** and every row must then only *match*. If this row's
//!   cost scales with pattern complexity rather than row count, the cache is
//!   not being hit.
//! * `replace_constant` — the same shape for `REPLACE`, whose replacement now
//!   goes through `CompiledPattern::replace_all` and the XPath F&O §5.6.2
//!   replacement parser rather than the `regex` crate's own `$N` syntax.
//! * `regex_dynamic_unique` — a pattern argument that differs per row, so
//!   every row is a cache **miss** and pays a full compile. Laid beside
//!   `regex_constant`, it is the control that shows the hit path is real.
//!
//! Both row counts are parameterized, and rayon's global pool is pinned to a
//! fixed size before the first query. The evaluator forks a per-chunk context
//! whose geometry follows `rayon::current_num_threads()`, so leaving the pool
//! implicit lets the numbers move with background rayon work on the same host.
//! The pin is global rather than a scoped pool because
//! [`NativeSparqlEngine`] holds a `RefCell` plan cache and is therefore
//! `!Sync`; it cannot be captured by a rayon `install` closure, so the pool
//! the main-thread evaluation drives must be the shared one.
//!
//! A second group, `regex_long_literals`, filters 2,048 literals of 4 KiB of
//! lowercase filler, one in sixteen ending with the text every pattern matches,
//! through one constant `REGEX` each. It measures the required-literal
//! prefilter `CompiledPattern::is_match` runs in front of the `regex` engine
//! (built without its own literal prefilter): `needle` (a literal),
//! `foo.*bar` (a literal prefix), `\d{4}-\d{2}` (a required `-` a bounded
//! distance into the match), `NEEDLE` under `i`, and `[a-z]{25}` (no
//! literal: the control, which no literal matches, so the engine walks every
//! byte).
//!
//! Report-only, `cargo bench -p purrdf-sparql-eval --bench regex_eval` (the
//! `make bench` lane) — excluded from `make check`. No timing is asserted.

use purrdf_testkit::text::lowercase_filler as filler;
use std::sync::Arc;

use purrdf_core::{
    RdfDataset, RdfDatasetBuilder, RdfLiteral, SparqlEngine, SparqlRequest, SparqlResult,
};
use purrdf_sparql_eval::NativeSparqlEngine;
use purrdf_testkit::bench::{Bench, BenchmarkId, Throughput, bench_group, bench_main, black_box};
use purrdf_testkit::rng::SplitMix64;

const EX: &str = "https://example.org/";
const ROW_COUNTS: &[usize] = &[1_000, 10_000];

/// One `ex:name "Name{i}"` triple and one distinct `ex:pat "^Name{i}$"` literal
/// per subject, generated by a counter (no RNG, no iteration-order dependence).
fn name_dataset(rows: usize) -> Arc<RdfDataset> {
    let mut b = RdfDatasetBuilder::new();
    let p_name = b.intern_iri(&format!("{EX}name"));
    let p_pat = b.intern_iri(&format!("{EX}pat"));
    for i in 0..rows {
        let subject = b.intern_iri(&format!("{EX}s{i}"));
        let name = b.intern_literal(RdfLiteral::simple(format!("Name{i}")));
        b.push_quad(subject, p_name, name, None);
        let pattern = b.intern_literal(RdfLiteral::simple(format!("^Name{i}$")));
        b.push_quad(subject, p_pat, pattern, None);
    }
    b.freeze().expect("freeze regex dataset")
}

/// The three measured query shapes as `(case name, query text)`. Each pattern
/// matches every row, so every case does exactly `rows` units of row work.
fn queries() -> [(&'static str, String); 3] {
    [
        (
            "regex_constant",
            format!(
                "SELECT ?s WHERE {{ ?s <{EX}name> ?n . \
                 FILTER(REGEX(?n, \"^Name[0-9]+$\")) }}"
            ),
        ),
        (
            "replace_constant",
            format!(
                "SELECT (REPLACE(?n, \"^Name\", \"Item\") AS ?m) WHERE {{ \
                 ?s <{EX}name> ?n }}"
            ),
        ),
        (
            "regex_dynamic_unique",
            format!(
                "SELECT ?s WHERE {{ ?s <{EX}name> ?n . ?s <{EX}pat> ?pat . \
                 FILTER(REGEX(?n, ?pat)) }}"
            ),
        ),
    ]
}

/// Run one query and return its solution count, panicking rather than silently
/// benchmarking an empty result.
fn run(engine: &NativeSparqlEngine, ds: &Arc<RdfDataset>, query: &str) -> usize {
    let result = engine
        .query(
            ds,
            SparqlRequest {
                query,
                base_iri: None,
                substitutions: &[],
            },
        )
        .expect("regex benchmark query evaluates");
    match result {
        SparqlResult::Solutions { rows, .. } => rows.len(),
        SparqlResult::Graph(graph) => graph.quad_count(),
        SparqlResult::Boolean(_) => 0,
    }
}

fn bench_regex_eval(c: &mut Bench) {
    // Pin rayon's global worker count once, before the first query: the
    // evaluator forks a per-chunk context whose geometry tracks
    // `rayon::current_num_threads()`, so an implicit pool would let the numbers
    // drift with background rayon work. A scoped `install` pool is not an
    // option here — `NativeSparqlEngine` holds a `RefCell` plan cache and is
    // `!Sync`, so it cannot be captured by an `install` closure.
    let threads = std::thread::available_parallelism().map_or(1, std::num::NonZero::get);
    rayon::ThreadPoolBuilder::new()
        .num_threads(threads)
        .build_global()
        .expect("the benchmark must own rayon's global pool so its thread count is pinned");
    assert_eq!(
        rayon::current_num_threads(),
        threads,
        "the pinned global pool must report the size this benchmark asked for"
    );

    let engine = NativeSparqlEngine::new();
    let queries = queries();

    let mut group = c.benchmark_group("regex_eval");
    // Whole-query evaluations run milliseconds; keep sampling light like
    // `query_eval` so the full matrix stays tractable.
    group.sample_size(10);

    for &rows in ROW_COUNTS {
        let ds = name_dataset(rows);
        for (label, query) in &queries {
            // Warm the plan cache and prove the fixture does work: a regression
            // that emptied the result would otherwise benchmark a no-op.
            let observed = run(&engine, &ds, query);
            assert!(
                observed >= rows,
                "case {label} returned {observed} rows (< {rows}) — the benchmark would be a no-op"
            );
            group.throughput(Throughput::Elements(rows as u64));
            group.bench_with_input(BenchmarkId::new(*label, rows), &rows, |bencher, _| {
                bencher.iter(|| {
                    let count = run(black_box(&engine), black_box(&ds), black_box(query));
                    black_box(count)
                });
            });
        }
    }
    group.finish();
}

/// The text every `regex_long_literals` pattern but the control matches in.
const MATCH_TAIL: &str = " foo needle bar 2026-09";

/// Literals in the long-literal dataset, and how many carry [`MATCH_TAIL`].
const LONG_ROWS: usize = 2048;
const LONG_MATCHES: usize = LONG_ROWS / 16;

/// `LONG_ROWS` subjects with one 4 KiB `ex:text` literal each; every sixteenth
/// ends with [`MATCH_TAIL`]. Seeded, so the dataset is the same every run.
fn long_literal_dataset() -> Arc<RdfDataset> {
    let mut rng = SplitMix64::new(0x0047_2600_BE4C_0002);
    let mut b = RdfDatasetBuilder::new();
    let p_text = b.intern_iri(&format!("{EX}text"));
    for i in 0..LONG_ROWS {
        let subject = b.intern_iri(&format!("{EX}doc{i}"));
        let mut text = filler(&mut rng, 4096);
        if i % 16 == 0 {
            text.push_str(MATCH_TAIL);
        }
        let literal = b.intern_literal(RdfLiteral::simple(text));
        b.push_quad(subject, p_text, literal, None);
    }
    b.freeze().expect("freeze long-literal regex dataset")
}

/// `(case name, SPARQL string literal of the pattern, flags, rows)`.
const LONG_CASES: &[(&str, &str, &str, usize)] = &[
    ("literal", "needle", "", LONG_MATCHES),
    ("prefix_unbounded", "foo.*bar", "", LONG_MATCHES),
    ("inner_bounded", r"\\d{4}-\\d{2}", "", LONG_MATCHES),
    ("literal_i", "NEEDLE", "i", LONG_MATCHES),
    ("control_no_literal", "[a-z]{25}", "", 0),
];

fn bench_regex_long_literals(c: &mut Bench) {
    let engine = NativeSparqlEngine::new();
    let ds = long_literal_dataset();
    let mut group = c.benchmark_group("regex_long_literals");
    group.sample_size(10);
    group.throughput(Throughput::Elements(LONG_ROWS as u64));
    for &(label, pattern, flags, rows) in LONG_CASES {
        let query = format!(
            "SELECT ?s WHERE {{ ?s <{EX}text> ?v . FILTER(REGEX(?v, \"{pattern}\", \"{flags}\")) }}"
        );
        // Untimed sanity: the filter keeps exactly the rows that carry the
        // tail, or the timed region would answer a different question.
        assert_eq!(run(&engine, &ds, &query), rows, "case {label}");
        group.bench_function(BenchmarkId::new(label, LONG_ROWS), |bencher| {
            bencher.iter(|| black_box(run(black_box(&engine), black_box(&ds), black_box(&query))));
        });
    }
    group.finish();
}

bench_group!(benches, bench_regex_eval, bench_regex_long_literals);
bench_main!(benches);
