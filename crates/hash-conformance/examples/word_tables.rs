//! Generate immutable metadata from the frozen alphabet, and record public-codec
//! vectors. Arguments: alphabet path, output Rust file, vector output file.
//! The output is formatted by rustfmt; neither input nor vocabulary is fetched.

use purrdf_hash::{
    blake3,
    hex::{self, Digest32},
    word_id::Reference,
};
use purrdf_hash_conformance::word_lookup::Lookup;
use purrdf_testkit::vectors::{Recorder, encode_str};
use std::error::Error;
use std::fmt::Write as _;

fn main() -> Result<(), Box<dyn Error>> {
    let args: Vec<_> = std::env::args_os().skip(1).collect();
    if args.len() != 3 {
        return Err("expected frozen alphabet, Rust output, vector output".into());
    }
    let bytes = std::fs::read(&args[0])?;
    if hex::encode(blake3::hash(&bytes).as_bytes())
        != "39a51de1fc00b10225ceeae54f6a7c1cd3ad7f191af0f92f5eb044132c534c05"
    {
        return Err("frozen alphabet identity mismatch".into());
    }
    let words: Vec<_> = std::str::from_utf8(&bytes)?.lines().collect();
    let lookup = Lookup::new(&words)?;
    let mut blob = String::new();
    let mut offsets = Vec::new();
    for word in &words {
        offsets.push(blob.len());
        blob.push_str(word);
    }
    offsets.push(blob.len());
    let (displacements, slots) = lookup.perfect_tables();
    let mut generated = String::from(
        "// SPDX-FileCopyrightText: 2016 Electronic Frontier Foundation\n// SPDX-FileCopyrightText: 2026 Blackcat Informatics® Inc. <paudley@blackcatinformatics.ca>\n// SPDX-License-Identifier: (MIT OR Apache-2.0 OR MulanPSL-2.0) AND CC-BY-4.0\n\n// Generated by word_tables from the frozen alphabet; do not edit.\n",
    );
    writeln!(
        generated,
        "pub(super) const MAX_WORD_LEN: usize = {};",
        words
            .iter()
            .map(|word| word.len())
            .max()
            .ok_or("empty dictionary")?
    )?;
    writeln!(
        generated,
        "const BLOB: &str = {blob:?};\nconst OFFSETS: [u16; 4097] = {offsets:?};\nconst DISPLACEMENTS: [i32; 1024] = {displacements:?};\nconst SLOTS: [u16; 4096] = {slots:?};"
    )?;
    generated.push_str("pub(super) fn word(index: u16) -> &'static str { let index=usize::from(index); &BLOB[usize::from(OFFSETS[index])..usize::from(OFFSETS[index+1])] }\npub(super) fn lookup(bytes: &[u8]) -> Option<u16> { let hash=crate::fnv::fnv1a64(bytes); let displacement=DISPLACEMENTS[hash as usize & 1023]; if displacement==0 { return None; } let slot=if displacement<0 { (-displacement-1) as usize } else { crate::mix::splitmix64_finalize(hash ^ displacement as u64) as usize & 4095 }; let index=SLOTS[slot]; (word(index).as_bytes()==bytes).then_some(index) }\n");
    std::fs::write(&args[1], generated)?;
    if !std::process::Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(&args[1])
        .status()?
        .success()
    {
        return Err("rustfmt refused generated word metadata".into());
    }
    let mut vectors = Recorder::new();
    vectors.comment("Frozen version-one word identities. Fields: canonical digest hex, payload count, canonical text.")?;
    vectors.comment("Recorded through the native owner; independent polynomial multiplication and bit laws are checked by the native conformance target.")?;
    for bytes in [
        [0; 32],
        [255; 32],
        std::array::from_fn(|index| index as u8),
        {
            let mut bytes = [0; 32];
            bytes[0] = 128;
            bytes
        },
        {
            let mut bytes = [0; 32];
            bytes[31] = 1;
            bytes
        },
    ] {
        let digest = Digest32::new(bytes);
        vectors.record(&[
            digest.to_hex(),
            "22".to_owned(),
            encode_str(&Reference::Full(digest).to_text()?),
        ])?;
    }
    let digest = Digest32::new(*blake3::hash(b"word-id-prefix-vectors").as_bytes());
    for payload in 1..=21 {
        vectors.record(&[
            digest.to_hex(),
            payload.to_string(),
            encode_str(&Reference::from_digest(digest, payload)?.to_text()?),
        ])?;
    }
    std::fs::write(&args[2], vectors.render())?;
    Ok(())
}
