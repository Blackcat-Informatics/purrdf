def self_test() -> int:
    cases: list[tuple[str, bool]] = []
    for name, files, exceptions, fragment in [
        (name, files, [], fragment) for name, files, fragment in SELF_TEST_CASES
    ] + EXCEPTION_CASES:
        findings = run_fixture(files, exceptions)
        if fragment is None:
            cases.append((name, findings == []))
        else:
            cases.append((name, len(findings) == 1 and fragment in findings[0]))
        if not cases[-1][1]:
            for finding in findings:
                print(f"  {finding}")
    # The registry table.
    scan = scan_workspace(drop_test_modules({"crates/beta/src/lib.rs": CLEAN_WORKSPACE["crates/beta/src/lib.rs"]}))
    table = readme_table(scan)
    readme = f"# Title\n\n{README_BEGIN}\nstale\n{README_END}\n\ntail\n"
    regenerated = readme_with_table(readme, table)
    cases.append(("a stale README table is regenerated between its markers", regenerated is not None and "stale" not in regenerated and regenerated.endswith("tail\n")))
    cases.append(("a README without the markers is reported, not rewritten", readme_with_table("# Title\n", table) is None))
    cases.append(("a current README table is left exactly as it is", regenerated is not None and readme_with_table(regenerated, table) == regenerated))
    cases.append(("the table lists each registration once, sorted by bytes", table.count("| `b\"") == 3 and table.index("gts-mmr-leaf") < table.index("merkle-root")))
    # The escapes the collector decodes.
    cases.append(("escapes decode to the bytes the compiler emits", decode_escapes(r"a\0b\x1f\u{e9}\n", False) == b"a\0b\x1f\xc3\xa9\n" and decode_escapes(r"\xff", True) == b"\xff"))
    failed = 0
    for name, held in cases:
        print(f"{'PASS' if held else 'FAIL'}: {name}")
        failed += not held
    if failed:
        print(f"check-hash-domains self-test: {failed} case(s) failed")
        return 1
    print("OK: check-hash-domains self-test")
    return 0


