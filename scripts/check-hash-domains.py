def main() -> int:
    arguments = sys.argv[1:]
    if arguments == ["--self-test"]:
        return self_test()
    if arguments not in ([], ["--write-readme"], ["--list"]):
        print("usage: check-hash-domains.py [--self-test | --write-readme | --list]", file=sys.stderr)
        return 2
    scan = scan_workspace(shipping_files(REPO_ROOT))
    if arguments == ["--list"]:
        for registration in sorted(scan.registrations, key=lambda registration: registration.data):
            print(f'{registration.file}:{registration.line}\t{registration.const}\tb"{render(registration.data)}"')
        return 0
    readme_path = REPO_ROOT / README_PATH
    readme = readme_path.read_text(encoding="utf-8")
    updated = readme_with_table(readme, readme_table(scan))
    try:
        exceptions = ledger_exceptions()
    except (OSError, tomllib.TOMLDecodeError) as exc:
        print(f"FAIL: {LEDGER_PATH}: {exc}")
        return 1
    findings = registry_findings(scan, exceptions)
    if updated is None:
        findings.append(f"FAIL: {README_PATH} has no `{README_BEGIN}` … `{README_END}` block")
    elif arguments == ["--write-readme"]:
        readme_path.write_text(updated, encoding="utf-8")
    elif updated != readme:
        findings.append(
            f"FAIL: the domain registry table in {README_PATH} is not the collected set; "
            "run `python3 scripts/check-hash-domains.py --write-readme`"
        )
    if findings:
        for finding in findings:
            print(finding)
        return 1
    print(
        f"OK: {len(scan.registrations)} hash domains registered through purrdf_hash::Domain, unique and "
        f"prefix-free; no raw domain literal reaches a hasher; {len(exceptions)} ledger-declared exception(s) "
        f"hold; the {README_PATH} registry table is current"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
