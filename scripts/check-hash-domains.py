"""Hold the workspace's hash domains unique, prefix-free and spelt through ``Domain``.

A hash domain is the byte string that names one preimage family: a digest of one
structure can never be read as a digest of another because each preimage starts
with (or carries, as its named ``domain`` part) its own domain. Every domain in
shipping code is a ``purrdf_hash::Domain`` constant, registered next to the
construction it separates. This gate collects every ``Domain::new(b"…")`` (and
``Domain::new("…".as_bytes())``) literal in shipping Rust — ``src/`` trees
outside ``#[cfg(test)]`` items and test-only modules — and fails on:

* **a duplicate**: two registrations with the same bytes. One family has one
  domain constant; a second construction needs its own domain;
* **a prefix violation**: one domain is a byte-prefix of another, so a preimage
  under the shorter one could begin like a preimage under the longer one;
* **an empty domain**, which is a prefix of every other one;
* **a raw domain literal** (rule ``raw-hash-domain``): a domain-shaped string or
  byte-string literal handed to a hasher, or declared as a domain constant,
  without going through ``Domain``. The rule, stated exactly:

  - a *hasher call* is ``.update(``, ``.chain_update(``, ``::digest(``,
    ``blake3::hash(``, ``derive_key(``, ``new_keyed(``, ``fnv1a64(``,
    ``fnv::fold(``, a framing helper (any ``frame…(``, ``frame_str(`` and
    ``frame_hash(`` included), a ``push_part(``/``append_framed(``/
    ``append_framed_part(``/``append_key_part(`` preimage part, ``.field(`` on
    a digest builder or a digest builder's ``Digest::new(``; a domain-shaped
    literal anywhere in the call's argument list is a hit;
  - a literal is *domain-shaped* when it holds a NUL byte, when it carries a
    version token (``v`` and digits after ``-``, ``.``, ``/``, ``:``, ``_`` or a
    space, ending the literal or followed by a separator), or when its bytes
    equal or begin with a registered domain;
  - a *domain constant* is a ``const`` or ``static`` whose name contains
    ``DOMAIN``, ``DIGEST_TAG``, ``IDENTITY_TAG`` or ``KEY_SALT``, or is ``D_``
    followed by an upper-case name, typed as a string or byte string. Its value
    is a hit unless it is an IRI (``RDFS_DOMAIN``, the vocabulary term, is a
    constant of that name and no hash domain) and not domain-shaped.

  Field labels inside a preimage (``b"slice-iri\\x1f"``), separators and
  protocol bytes are not domain-shaped and pass. Test code is out of scope: a
  test that recomputes a frozen digest from its raw preimage is an independent
  oracle, not a second spelling;
* **a shared domain** (rule ``shared-hash-domain``): a registered domain that
  appears in hasher calls of two or more functions of the file registering it —
  one domain opening two constructions. Openings of one constant from different
  files are not compared: they are the streaming and one-shot forms of one
  construction.

Exceptions are rows of the ``hash-domain`` job in ``helpers-ledger.toml`` whose
``detector`` is one of this gate's rules, each naming a documented anchor:

* ``shared-hash-domain`` sanctions the shared domain its ``symbol`` names;
* ``undomained-digest`` records a function that computes a published identity
  digest with no domain. There is no workspace-wide ``undomained-digest``
  refusal — a content address over raw bytes, an RDFC hash or a SPARQL ``MD5()``
  needs no domain, and no syntax tells those from an identity preimage — so the
  row is the record of a reviewed decision, and it is held true: the function
  must still compute a digest and name no ``Domain``.

A row that no longer matches its detector is STALE and fails, and a row without
an anchor fails; ``check-shared-helpers.py`` resolves the anchors through the
census and requires their documentation.

The registry table in ``crates/hash/README.md`` (between the
``hash-domain-registry`` markers) is the collected set; this gate fails when the
two differ, and ``--write-readme`` regenerates the table. ``--self-test`` runs
seeded workspaces through every rule, each refusal beside a valid neighbour that
passes. ``--list`` prints the collected set.
"""

