def run_fixture(files: dict[str, str], exceptions: list[dict] | None = None) -> list[str]:
    with tempfile.TemporaryDirectory(prefix="hash-domain-fixture-") as directory:
        root = Path(directory)
        for relative, text in files.items():
            path = root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        subprocess.run(["git", "init", "-q"], cwd=root, check=True)
        return registry_findings(scan_workspace(shipping_files(root)), exceptions)


